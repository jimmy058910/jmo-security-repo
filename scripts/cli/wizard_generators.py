"""
Artifact generators for the JMo Security wizard.

Extracted from wizard.py to reduce file size (959 → ~750 lines).

Functions:
- generate_makefile_target(): Creates Makefile .PHONY target
- generate_shell_script(): Creates standalone Bash script
- generate_github_actions(): Creates GitHub Actions YAML workflow
"""

from __future__ import annotations

import shlex
from pathlib import Path
from typing import TYPE_CHECKING, Any

from scripts.cli.jmo import __version__
from scripts.core.schedule_manager import reject_github_expression
from scripts.core.tool_registry import TOOL_MATRIX
from scripts.core.validation import GITLAB_DEFAULT_URL, gitlab_clone_base

if TYPE_CHECKING:
    pass

# Docker image configuration - a versioned tag, for reproducibility.
#
# DERIVED, not written down (#1075). This was a hand-maintained literal with the
# comment "This should be updated with each release"; it was bumped for v1.0.4
# and v1.0.5 and then missed v1.0.6, v1.0.7 and v1.0.8, so `jmo wizard` handed
# users a `docker run ... :v1.0.5` command while `jmo --version` said 1.0.8.
# The release bump touches jmo.py, pyproject.toml and docs/CLI_REFERENCE.md and
# never touched this file, which is why it decayed silently. Deriving it removes
# the failure mode instead of adding a fourth entry to that checklist.
JMO_DOCKER_IMAGE = "ghcr.io/jimmy058910/jmo-security"
JMO_DOCKER_TAG = f"v{__version__}"  # pinned to this release, not :latest
JMO_DOCKER_IMAGE_FULL = f"{JMO_DOCKER_IMAGE}:{JMO_DOCKER_TAG}"


def generate_makefile_target(config: Any, command: str) -> str:
    """
    Generate a Makefile target for security scanning.

    Args:
        config: Wizard configuration object
        command: Pre-generated jmotools command string

    Returns:
        Makefile targets: security-scan, security-report, security-clean
    """
    # make expands `$` in a recipe before /bin/sh sees it, so a literal one is
    # `$$`. `command` is already shell-quoted; this is make's layer on top.
    command = command.replace("$", "$$")
    prepare = "".join(
        f"\t{line}\n".replace("$", "$$") for line in _prepare_lines(config)
    )

    return f"""
# JMo Security Scan Target (generated by wizard)
.PHONY: security-scan
security-scan:
{prepare}\t{command}

.PHONY: security-report
security-report:
\tjmo report ./results

.PHONY: security-clean
security-clean:
\trm -rf results/
"""


def generate_shell_script(config: Any, command: str) -> str:
    """
    Generate a standalone shell script for security scanning.

    Args:
        config: Wizard configuration object
        command: Pre-generated jmotools command string

    Returns:
        Bash script content with shebang and error handling
    """
    prepare = "".join(f"{line}\n" for line in _prepare_lines(config))
    return f"""#!/usr/bin/env bash
# JMo Security Scan Script (generated by wizard)
set -euo pipefail

{prepare}{command}
"""


def _prepare_lines(config: Any) -> list[str]:
    """Shell lines that must run before a Docker-mode command, or none.

    A Linux engine creates a missing bind-mount source owned by root, and the
    image's user cannot write it, so the scan failed at its first write
    (#1307). The script and the make target create the directories first.
    """
    # Lazy: command_builder imports this module.
    from scripts.cli.wizard_flows.command_builder import docker_output_dirs

    dirs = docker_output_dirs(config)
    if not dirs:
        return []
    return [
        "# Docker creates a missing mount as root, which the image cannot write.",
        shlex.join(["mkdir", "-p", *dirs]),
    ]


def _gitlab_url_to_pass(raw: str | None) -> str | None:
    """The `--gitlab-url` a workflow needs for the wizard's GitLab URL, or None.

    None when it is gitlab.com, which `jmo scan` assumes. Otherwise the URL as
    `scan_gitlab_repo` clones from it: without the flag a self-hosted instance's
    project is cloned from gitlab.com, which is offered the instance's token.

    Raises:
        ValueError: The scan would refuse the URL. The message never repeats
            it, which may carry credentials typed into it.
    """
    try:
        url = gitlab_clone_base(raw)
    except ValueError as exc:
        raise ValueError(
            f"gitlab_url is a URL `jmo scan --gitlab-url` would refuse: {exc}"
        ) from None
    return None if url == GITLAB_DEFAULT_URL else url


def _checkout_path(path: str) -> str:
    """`path` as the workflow's checkout names it: relative to the repository.

    The wizard stores the IaC file resolved, an absolute path on this machine,
    and the workflow runs on a fresh checkout elsewhere. A path under the
    working directory (where the wizard runs, normally the repository root)
    becomes relative to it.

    Raises:
        ValueError: The file is outside the working directory, so the runner's
            checkout cannot hold it. The message never repeats the path: it is
            this machine's, and would otherwise reach a committed workflow.
    """
    cwd = Path.cwd().resolve()
    try:
        return (cwd / path).resolve().relative_to(cwd).as_posix()
    except ValueError:
        raise ValueError(
            "the IaC file is outside the working directory, and the workflow "
            "runs on a checkout of this repository: run the wizard from the "
            "repository that holds the file"
        ) from None


def _workflow_target_flags(target: Any) -> list[str]:
    """The flags naming the wizard's target in a workflow, each value quoted.

    One list for both modes: the Docker workflow runs `jmo` in the image as the
    job's container, on the same checkout, so its target flags are the native
    ones. Docker mode had its own list, which named only repo, image and url
    targets, so a GitLab, IaC or K8s workflow scanned nothing (#1554). Every
    value is `shlex.quote`d: it lands in a `run:` block, where an unquoted `&`
    in a URL put the scan in the background and `$(...)` ran a command. And no
    value may hold `${{`, which GitHub evaluates before the shell sees the line,
    quoted or not (#1552).
    """

    def q(value: str, name: str) -> str:
        reject_github_expression(value, f"target.{name}")
        return shlex.quote(value)

    if target.type == "repo":
        # The checkout, whatever the local repo_mode was: that describes the
        # wizard user's disk, not the one repository this workflow runs on.
        # `--repos-dir .` scanned each subdirectory as its own repository
        # and never the root's files; targets and tsv emitted no target.
        return ["--repo ."]
    if target.type == "image":
        return (
            [f"--image {q(target.image_name, 'image_name')}"]
            if target.image_name
            else []
        )
    if target.type == "url":
        return [f"--url {q(target.url, 'url')}"] if target.url else []
    if target.type == "iac":
        flag = {
            "terraform": "--terraform-state",
            "cloudformation": "--cloudformation",
            "k8s-manifest": "--k8s-manifest",
        }[target.iac_type]
        return [f"{flag} {q(_checkout_path(target.iac_path), 'iac_path')}"]
    flags: list[str] = []
    if target.type == "gitlab":
        gitlab_url = _gitlab_url_to_pass(target.gitlab_url)
        if gitlab_url:
            flags.append(f"--gitlab-url {q(gitlab_url, 'gitlab_url')}")
        if target.gitlab_repo:
            flags.append(f"--gitlab-repo {q(target.gitlab_repo, 'gitlab_repo')}")
    elif target.type == "k8s":
        if target.k8s_context:
            flags.append(f"--k8s-context {q(target.k8s_context, 'k8s_context')}")
        if target.k8s_all_namespaces:
            flags.append("--k8s-all-namespaces")
        elif target.k8s_namespace:
            flags.append(f"--k8s-namespace {q(target.k8s_namespace, 'k8s_namespace')}")
    return flags


def generate_github_actions(config: Any) -> str:
    """
    Generate a GitHub Actions workflow for security scanning.

    Creates either Docker-based or native workflow depending on config.use_docker.
    Supports all 6 target types: repo, image, iac, url, gitlab, k8s.

    Args:
        config: Wizard configuration object

    Returns:
        GitHub Actions YAML workflow content
    """
    # Lazy: wizard_flows imports this module (command_builder), so a top-level
    # import of the package from here would be circular.
    from scripts.cli.wizard_flows.config_models import scan_defaults

    default_threads, default_timeout = scan_defaults()
    threads = config.threads or default_threads
    timeout = config.timeout or default_timeout
    # `jmo scan` defines no --fail-on (it abbreviates to --fail-on-store-error
    # and the severity is then an unrecognised argument); a threshold is what
    # `jmo ci` is for. Same rule as command_builder.build_command_parts.
    subcommand = "ci" if config.fail_on else "scan"

    # Detect required secrets based on target type
    setup_steps = []
    env_vars = []

    if config.target.type == "gitlab":
        setup_steps.append("""
      - name: Configure GitLab Access
        env:
          GITLAB_TOKEN: ${{ secrets.GITLAB_TOKEN }}
        run: echo "GITLAB_TOKEN configured for GitLab scanning"
""")
        env_vars.append("GITLAB_TOKEN: ${{ secrets.GITLAB_TOKEN }}")

    elif config.target.type == "k8s":
        setup_steps.append("""
      - name: Configure kubectl
        run: |
          mkdir -p ~/.kube
          echo "${{ secrets.KUBECONFIG }}" > ~/.kube/config
          kubectl config view
""")

    setup_steps_str = "".join(setup_steps)
    env_section = (
        f"\n        env:\n          {chr(10).join('          ' + e for e in env_vars)}"
        if env_vars
        else ""
    )

    if config.use_docker:
        # Docker-based workflow
        scan_cmd_lines = [
            f"jmo {subcommand} --results-dir results",
            *_workflow_target_flags(config.target),
            f"--threads {threads}",
            f"--timeout {timeout}",
        ]

        if config.fail_on:
            scan_cmd_lines.append(f"--fail-on {config.fail_on}")
        scan_cmd = " \\\n            ".join(scan_cmd_lines)

        return f"""name: Security Scan
on:
  push:
    branches: [main]
  pull_request:
  schedule:
    - cron: '0 0 * * 0'  # Weekly

jobs:
  security-scan:
    runs-on: ubuntu-latest
    container:
      image: {JMO_DOCKER_IMAGE_FULL}
    steps:
      - uses: actions/checkout@v4
{setup_steps_str}
      - name: Run Security Scan{env_section}
        run: |
          {scan_cmd}

      - name: Upload Results
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: security-results
          path: results/summaries/

      - name: Upload SARIF
        if: always()
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: results/summaries/findings.sarif
"""
    else:
        # Native workflow
        scan_cmd_lines = [
            f"jmo {subcommand}",
            *_workflow_target_flags(config.target),
            f"--threads {threads}",
            f"--timeout {timeout}",
            "--results-dir results",
        ]

        if config.fail_on:
            scan_cmd_lines.append(f"--fail-on {config.fail_on}")
        scan_cmd = " \\\n            ".join(scan_cmd_lines)

        tools_list = ", ".join(TOOL_MATRIX)

        # Add secrets note if needed
        secrets_note = ""
        if config.target.type == "gitlab":
            secrets_note = (
                "\n    # NOTE: Add GITLAB_TOKEN secret to repository settings"
            )
        elif config.target.type == "k8s":
            secrets_note = "\n    # NOTE: Add KUBECONFIG secret to repository settings"

        return f"""name: Security Scan{secrets_note}
on:
  push:
    branches: [main]
  pull_request:
  schedule:
    - cron: '0 0 * * 0'  # Weekly

jobs:
  security-scan:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.12'

      - name: Install JMo Security
        run: pip install "jmo-security[yara]"

      - name: Install Security Tools
        run: |
          # Install the tool matrix: jmo tools install
          # Tools: {tools_list}
          # See: https://github.com/jimmy058910/jmo-security-repo#tool-installation
          jmo tools install --yes
{setup_steps_str}
      - name: Run Security Scan{env_section}
        run: |
          {scan_cmd}

      - name: Upload Results
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: security-results
          path: results/summaries/

      - name: Upload SARIF
        if: always()
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: results/summaries/findings.sarif
"""
